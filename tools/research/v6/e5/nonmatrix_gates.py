"""The E5 pre-treatment gates at non-matrix seeds (review Sec L gates 5-7).

Every gate runs named scenarios only, at seeds outside the matrix's 1..32,
and records pass/fail evidence -- identities, hashes and counts -- never a
gameplay outcome metric of the treatment. Each has a sensitivity case that
must *fail*, so a passing gate is shown able to see what it checks.

* **P5 inertness** (review Sec F, Revision 1 decision R1-5). For every E5
  pairing that contains a fixture following the single-location core-inference
  contract, the frozen fixture and a *test-only* offset-aware copy (the same
  code with its enemy-core adoption corrected by its own spawn offset) must
  play byte-identical tick records under the primary treatment. The copies
  are generated by ``offset_aware_source`` into a temporary data root and
  never enter the matrix, the populations or the analysis. Sensitivity: with
  the spawn moved to ``core_base - 2`` (a scratch patch of the resolver), at
  least one pairing must differ.
* **Observation delta** (review Sec L gate 5). For every E5 pairing, each
  entrant's first observation under a treatment differs from the parent's only
  in ``self_anchor`` (-1) and in each visible enemy anchor (-1). Sensitivity:
  comparing the parent with itself shifted by the patch above must fail.
* **D9 real-fixture gate** (G.5). E3's D9 scenarios, unchanged, under T-E5:
  the real repair and disrupt guards against scripted adversaries are never
  captured. Sensitivity: the whole-tick E2 Ruleset captures the repair guard.
"""

