"""Independent cross-version evaluation identity extraction guards.

The expected digests in this module are not generated by
``battle_engine.result_model.stable_id``.  Payloads are specified literally
and hashed by the small reference encoder below so production identity and
history reconstruction can drift independently and still be detected.
"""

