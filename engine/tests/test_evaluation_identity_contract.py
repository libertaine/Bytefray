@pytest.mark.parametrize("version", (4, 5, 7))
def test_pairwise_schedule_and_condition_producer_agree_with_independent_reference_and_history(
    version: int, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    payload = _identity_payloads()[version]
    request = _request_for_version(version, tmp_path / f"matrix-v{version}")
    identities = _identities(local=True)
    specs = {agent_id: SimpleNamespace(name=agent_id) for agent_id in identities}
    # V6 Phase 3G: the matrix compiler lives in ``evaluation_planning``, so
    # its ``agent_identity`` seam is the one a synthetic spec must replace.
    # ``evaluation.build_matrix`` below is still called through the permanent
    # facade, which re-exports the very same function object.
    monkeypatch.setattr(planning, "agent_identity", lambda spec: identities[spec.name])
    conditions_fingerprint = "evaluation-conditions_89abcdef0123456789abcdef"
    alignment_mode = payload["arena_alignment_mode"]

    matrix = evaluation.build_matrix(
        request,
        EXPECTED_EVALUATION_IDS[version],
        specs,
        conditions_fingerprint,
        payload["rules_compatibility_id"],
        alignment_mode,
    )
    assert matrix

    for cell in matrix:
        schedule_payload: dict[str, Any] = {
            "evaluation_id": EXPECTED_EVALUATION_IDS[version],
            "role": cell.subject_role,
            "subject_id": cell.subject_id,
            "opponent_id": cell.opponent_id,
            "seed": cell.seed,
            "orientation": cell.orientation,
            "ordinal": cell.matrix_ordinal,
        }
        if version in (5, 7):
            schedule_payload["placement_id"] = cell.placement_id
        assert cell.schedule_id == _reference_stable_id("evaluation-cell", schedule_payload)

        condition_payload: dict[str, Any] = {
            "opponent": identities[cell.opponent_id],
            "seed": cell.seed,
            "effective_conditions": conditions_fingerprint,
            "rules_compatibility_id": payload["rules_compatibility_id"],
            "condition_occurrence_index": cell.condition_occurrence_index,
            "orientation": cell.orientation,
            "arena_alignment_mode": alignment_mode,
        }
        if version in (5, 7):
            condition_payload["placement"] = {
                "placement_id": cell.placement_id,
                "subject_start": cell.subject_start,
                "opponent_start": cell.opponent_start,
            }
        assert cell.condition_fingerprint == _reference_stable_id(
            "evaluation-condition", condition_payload
        )

    summary = _write_and_adapt(
        tmp_path,
        f"matrix-history-v{version}",
        _artifact_from_payload(
            version,
            payload,
            EXPECTED_EVALUATION_IDS[version],
            cells=[_raw_pairwise_cell(cell) for cell in matrix],
            conditions_fingerprint=conditions_fingerprint,
        ),
    )
    assert HealthCode.PLANNED_IDENTITY_INCONSISTENT not in summary.health.codes
    assert HealthCode.CONDITION_FINGERPRINT_INCONSISTENT not in summary.health.codes
