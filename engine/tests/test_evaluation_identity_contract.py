@pytest.mark.parametrize("version", (2, 3))
def test_pre_orientation_condition_fingerprint_goldens_remain_history_verifiable(
    version: int, tmp_path: Path
) -> None:
    payload = _identity_payloads()[version]
    conditions_fingerprint = "evaluation-conditions_0123456789abcdef01234567"
    opponent = payload["opponents"][1]
    cells: list[dict[str, Any]] = []
    for occurrence, expected in enumerate(HISTORICAL_CONDITION_IDS[version]):
        fingerprint_payload = {
            "opponent": opponent,
            "seed": 1,
            "effective_conditions": conditions_fingerprint,
            "rules_compatibility_id": payload["rules_compatibility_id"],
            "condition_occurrence_index": occurrence,
        }
        assert _reference_stable_id("evaluation-condition", fingerprint_payload) == expected
        cells.append(
            {
                "schedule_id": f"historical-v{version}-{occurrence}",
                "subject_role": "candidate",
                "subject_id": "candidate",
                "opponent_id": "opp-a",
                "seed": 1,
                "status": "pending",
                "opponent_index": 1 + occurrence,
                "seed_index": 0,
                "matrix_ordinal": occurrence + 1,
                "condition_occurrence_index": occurrence,
                "condition_fingerprint": expected,
            }
        )

    summary = _write_and_adapt(
        tmp_path,
        f"conditions-v{version}",
        _artifact_from_payload(
            version,
            payload,
            EXPECTED_EVALUATION_IDS[version],
            cells=cells,
            conditions_fingerprint=conditions_fingerprint,
        ),
    )
    assert HealthCode.CONDITION_FINGERPRINT_INCONSISTENT not in summary.health.codes


