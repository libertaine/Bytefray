def _reference_stable_id(prefix: str, payload: dict[str, Any]) -> str:
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return f"{prefix}_{hashlib.sha256(encoded).hexdigest()[:24]}"


def _identity(agent_id: str, marker: str, *, local: bool) -> dict[str, Any]:
    identity: dict[str, Any] = {
        "agent_id": agent_id,
        "kind": "python",
        "api_version": 2,
        "agent_version": "1.0",
        "entry_point": "agent.py:create_agent",
        "source_sha256": marker * 64,
    }
    if local:
        identity["local_source_fingerprint"] = marker.upper() * 64
    return identity


def _identities(*, local: bool) -> dict[str, dict[str, Any]]:
    return {
        "candidate": _identity("candidate", "a", local=local),
        "baseline": _identity("baseline", "b", local=local),
        "opp-a": _identity("opp-a", "c", local=local),
        "opp-b": _identity("opp-b", "d", local=local),
    }


def _conditions(arena_size: int) -> dict[str, Any]:
    return {
        "tick_limit": 37,
        "arena_size": arena_size,
        "action_budget": 8,
        "win_mode": "score_fallback",
        "weights": {
            "alive": 1.0,
            "kill": 5.0,
            "territory": 1.0,
            "territory_bucket": 64,
        },
        "agent_api_version": 2,
        "subject_slot": "A",
        "opponent_slot": "B",
        "entrant_order": ["A", "B"],
        "runtime_kind": "python",
        "supervision": "unsupervised",
        "tracing": "untraced",
    }


def _identity_payloads() -> dict[int, dict[str, Any]]:
    legacy = _identities(local=False)
    current = _identities(local=True)
    legacy_opponents = [legacy["opp-b"], legacy["opp-a"], legacy["opp-a"]]
    current_opponents = [current["opp-b"], current["opp-a"], current["opp-a"]]
    seeds = [1, 7, 1]
    common_legacy = {
        "candidate": legacy["candidate"],
        "baseline": legacy["baseline"],
        "opponents": legacy_opponents,
        "seeds": seeds,
        "ticks": 37,
        "effective_conditions": _conditions(4096),
        "rules_compatibility_id": "evaluation-rules-1",
    }
    common_current = {
        "candidate": current["candidate"],
        "baseline": current["baseline"],
        "opponents": current_opponents,
        "seeds": seeds,
        "ticks": 37,
        "effective_conditions": _conditions(4096),
    }
    return {
        # v2 predates whole-tree local source fingerprints and entrant
        # orientation.  Opponent/seed ordering and duplicates are still
        # identity-bearing.
        2: {"identity_version": 2, **common_legacy},
        # v3 adds local_source_fingerprint to every planned agent identity.
        3: {
            "identity_version": 3,
            **common_current,
            "rules_compatibility_id": "evaluation-rules-1",
        },
        # v4 adds orientation and arena-alignment methodology siblings.
        4: {
            "identity_version": 4,
            **common_current,
            "rules_compatibility_id": BYTEFRAY_RULESET_ID,
            "orientation_mode": "both",
            "arena_alignment_mode": "fixed",
        },
        # v5 selects historical Ruleset-v2 methodology and hashes the exact
        # standard 1v1 placement set.
        5: {
            "identity_version": 5,
            **common_current,
            "rules_compatibility_id": BYTEFRAY_RULESET_V2_ID,
            "orientation_mode": "both",
            "arena_alignment_mode": "ruleset_v2_standard_placements",
            "placements": [
                {"placement_id": "opposed", "subject_start": 0, "opponent_start": 2048},
                {"placement_id": "quarter", "subject_start": 0, "opponent_start": 1024},
                {
                    "placement_id": "opposed-shifted",
                    "subject_start": 1024,
                    "opponent_start": 3072,
                },
            ],
        },
        # v6 is a historical/read-only group identity.  It deliberately has
        # no orientation_mode; ordered seat assignments were the generalized
        # scheduler-order axis.  This test does not invoke retired execution.
        6: {
            "identity_version": 6,
            "candidate": current["candidate"],
            "baseline": None,
            "opponents": current_opponents,
            "seeds": seeds,
            "ticks": 37,
            "effective_conditions": _conditions(4096),
            "rules_compatibility_id": BYTEFRAY_RULESET_V2_ID,
            "arena_alignment_mode": "ruleset_v2_group_standard_layouts",
            "group": True,
            "layouts": [
                {"layout_id": "spread", "seat_starts": [0, 1024, 2048, 3072]},
                {"layout_id": "spread-shifted", "seat_starts": [512, 1536, 2560, 3584]},
                {"layout_id": "close", "seat_starts": [0, 512, 1024, 1536]},
            ],
        },
        # v7 is the executable stable-v4 methodology.  The seed-derived
        # geometry is copied from frozen Ruleset vectors, not resolved by the
        # production helper while the test runs; duplicate seed 1 is retained.
        7: {
            "identity_version": 7,
            "candidate": current["candidate"],
            "baseline": current["baseline"],
            "opponents": current_opponents,
            "seeds": seeds,
            "ticks": 37,
            "effective_conditions": _conditions(512),
            "rules_compatibility_id": BYTEFRAY_RULESET_V4_ID,
            "orientation_mode": "both",
            "arena_alignment_mode": "ruleset_v4_seeded_placements",
            "placements": [
                {"seed": 1, "subject_start": 380, "opponent_start": 263},
                {"seed": 7, "subject_start": 324, "opponent_start": 167},
                {"seed": 1, "subject_start": 380, "opponent_start": 263},
            ],
        },
    }


