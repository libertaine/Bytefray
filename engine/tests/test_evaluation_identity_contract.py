def _request_for_version(version: int, output_dir: Path) -> evaluation.EvaluationRequest:
    ruleset_id = {
        4: BYTEFRAY_RULESET_ID,
        5: BYTEFRAY_RULESET_V2_ID,
        7: BYTEFRAY_RULESET_V4_ID,
    }[version]
    return evaluation.EvaluationRequest(
        candidate_id="candidate",
        baseline_id="baseline",
        opponent_ids=("opp-b", "opp-a", "opp-a"),
        seeds=(1, 7, 1),
        output_dir=output_dir,
        ticks=37,
        both_orientations=True,
        ruleset_id=ruleset_id,
        arena_size=512 if version == 7 else 4096,
    )


def _conditions_model(payload: dict[str, Any]) -> evaluation.EffectiveConditions:
    raw = payload["effective_conditions"]
    return evaluation.EffectiveConditions(
        tick_limit=raw["tick_limit"],
        arena_size=raw["arena_size"],
        action_budget=raw["action_budget"],
        win_mode=raw["win_mode"],
        weights=dict(raw["weights"]),
        agent_api_version=raw["agent_api_version"],
        subject_slot=raw["subject_slot"],
        opponent_slot=raw["opponent_slot"],
        entrant_order=tuple(raw["entrant_order"]),
        runtime_kind=raw["runtime_kind"],
        supervision=raw["supervision"],
        tracing=raw["tracing"],
    )


def _artifact_from_payload(
    version: int,
    payload: dict[str, Any],
    evaluation_id: str,
    *,
    cells: list[dict[str, Any]] | None = None,
    conditions_fingerprint: str | None = None,
) -> dict[str, Any]:
    opponent_ids = [identity["agent_id"] for identity in payload["opponents"]]
    data: dict[str, Any] = {
        "schema": evaluation.SCHEMA_NAME,
        "schema_version": version,
        "identity_version": version,
        "evaluation_id": evaluation_id,
        "candidate_id": payload["candidate"]["agent_id"],
        "baseline_id": (
            payload["baseline"]["agent_id"] if payload["baseline"] is not None else None
        ),
        "opponent_ids": opponent_ids,
        "seeds": list(payload["seeds"]),
        "ticks": payload["ticks"],
        "matrix_size": len(cells or ()),
        "planned_identities": {
            "candidate": payload["candidate"],
            "baseline": payload["baseline"],
            "opponents": payload["opponents"],
        },
        "effective_conditions": payload["effective_conditions"],
        "rules_compatibility_id": payload["rules_compatibility_id"],
        "created_at": "2026-09-20T00:00:00.000000Z",
        "updated_at": "2026-09-20T00:00:00.000000Z",
        "finished_at": None,
        "lifecycle_state": "running",
        "abort_reason": None,
        "abort_detail": None,
        "execution_contexts": [],
        "project": {},
        "cells": cells or [],
        "aggregates": [],
        "comparison": [],
        "complete": False,
    }
    if "orientation_mode" in payload:
        data["orientation_mode"] = payload["orientation_mode"]
    if "arena_alignment_mode" in payload:
        data["arena_alignment_mode"] = payload["arena_alignment_mode"]
    if payload.get("group") is True:
        data["group"] = True
        data["roster_agent_ids"] = [payload["candidate"]["agent_id"], *opponent_ids]
    if conditions_fingerprint is not None:
        data["effective_conditions_fingerprint"] = conditions_fingerprint
    return data


def _write_and_adapt(tmp_path: Path, name: str, data: dict[str, Any]):
    path = tmp_path / name / "evaluation.json"
    path.parent.mkdir(parents=True)
    path.write_text(json.dumps(data), encoding="utf-8")
    return adapt_v2(path)


@pytest.mark.parametrize("version", (2, 3, 4, 5, 6, 7))
def test_cross_version_evaluation_identity_golden_and_history_agreement(
    version: int, tmp_path: Path
) -> None:
    payload = _identity_payloads()[version]
    expected = EXPECTED_EVALUATION_IDS[version]

    assert [item["agent_id"] for item in payload["opponents"]] == [
        "opp-b",
        "opp-a",
        "opp-a",
    ]
    assert payload["seeds"] == [1, 7, 1]
    assert _reference_stable_id("evaluation-v2", payload) == expected
    assert (
        build_evaluation_id(
            identity_version=version,
            candidate=payload["candidate"],
            baseline=payload["baseline"],
            opponents=payload["opponents"],
            seeds=payload["seeds"],
            ticks=payload["ticks"],
            effective_conditions=payload["effective_conditions"],
            rules_compatibility_id=payload["rules_compatibility_id"],
            orientation_mode=payload.get("orientation_mode"),
            arena_alignment_mode=payload.get("arena_alignment_mode"),
            group=payload.get("group") is True,
            layouts=payload.get("layouts"),
            placements=payload.get("placements"),
        )
        == expected
    )

    # Only v7 is a currently executable producer recipe.  Versions 2-6 are
    # checked as independently specified historical artifacts; calling the
    # producer's unreachable retired-Ruleset/group branches here would turn
    # dead execution plumbing into a compatibility promise.
    if version == 7:
        request = _request_for_version(version, tmp_path / f"producer-v{version}")
        producer_id = evaluation.EvaluationService()._evaluation_id(
            request,
            _identities(local=True),
            _conditions_model(payload),
        )
        assert producer_id == expected

    summary = _write_and_adapt(
        tmp_path,
        f"history-v{version}",
        _artifact_from_payload(version, payload, expected),
    )
    assert HealthCode.PLANNED_IDENTITY_INCONSISTENT not in summary.health.codes


